def describe(preset, max_items=None):
    """给界面用的一行说明。"""
    if not preset:
        return "（未设置）"
    keys = sorted(preset)
    if not keys:
        return "（未设置）"
    if max_items is not None and len(keys) > max_items:
        keys = keys[:max_items]
    return "  ".join("%d节 %s-%s" % (k, preset[k][0], preset[k][1]) for k in keys)
